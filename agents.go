package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// AgentsFileName is the guide `tq init` keeps inside the task directory, and
// the file it points at from the repository's own agent instructions.
const AgentsFileName = "AGENTS.md"

// rootDocNames are the repository-level agent instruction files that get a
// pointer to the task guide. The first one is created when none exists.
var rootDocNames = []string{"AGENTS.md", "CLAUDE.md"}

const (
	taskSectionTitle = "Task management"
	generatedNotice  = "<!-- Generated by `tq init`. Edits are overwritten. -->"
)

// SyncAgentsDocs writes the task-directory guide and makes sure the
// repository's agent instructions point at it. workingDir is where the command
// was run, which is what locates the project when it is not a Git repository.
// It returns the files it wrote, so the CLI can say what changed, and rewrites
// nothing that is already right.
func SyncAgentsDocs(store *Store, workingDir string) ([]string, error) {
	root := docRoot(workingDir)

	link, err := filepath.Rel(root, filepath.Join(store.Dir, AgentsFileName))
	if err != nil {
		// Different volumes, say: an absolute path still works as a link.
		link = filepath.Join(store.Dir, AgentsFileName)
	}
	link = filepath.ToSlash(link)

	var written []string

	guide := filepath.Join(store.Dir, AgentsFileName)
	changed, err := writeIfChanged(guide, taskGuide(store.Dir))
	if err != nil {
		return nil, err
	}
	if changed {
		written = append(written, guide)
	}

	for _, name := range rootDocNames {
		path := filepath.Join(root, name)
		existing, err := os.ReadFile(path)
		if err != nil {
			if !os.IsNotExist(err) {
				return nil, err
			}
			continue // only files that already exist are updated
		}

		updated, ok := withTaskSection(string(existing), link)
		if !ok {
			continue
		}
		if _, err := writeIfChanged(path, []byte(updated)); err != nil {
			return nil, err
		}
		written = append(written, path)
	}

	// Nothing to point from yet: start the conventional file.
	if !containsAnyRootDoc(root) {
		path := filepath.Join(root, rootDocNames[0])
		content, _ := withTaskSection("", link)
		if _, err := writeIfChanged(path, []byte(content)); err != nil {
			return nil, err
		}
		written = append(written, path)
	}

	return written, nil
}

// docRoot is where the repository's agent instructions live: the root of the
// enclosing Git repository, falling back to the directory the command ran in.
func docRoot(workingDir string) string {
	dir, err := filepath.Abs(workingDir)
	if err != nil {
		dir = workingDir
	}
	if root, ok := repositoryRoot(dir); ok {
		return root
	}
	return dir
}

func containsAnyRootDoc(root string) bool {
	for _, name := range rootDocNames {
		if _, err := os.Stat(filepath.Join(root, name)); err == nil {
			return true
		}
	}
	return false
}

func writeIfChanged(path string, content []byte) (bool, error) {
	if existing, err := os.ReadFile(path); err == nil && string(existing) == string(content) {
		return false, nil
	} else if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	if err := os.WriteFile(path, content, 0o644); err != nil {
		return false, err
	}
	return true, nil
}

// withTaskSection returns doc with a "Task management" section pointing at
// link, and reports whether anything needed changing. An existing section is
// rewritten (the task directory may have moved); an existing link is left
// alone.
func withTaskSection(doc, link string) (string, bool) {
	section := fmt.Sprintf("See [%s](%s)", AgentsFileName, link)
	if strings.Contains(doc, "("+link+")") {
		return doc, false
	}

	// A second level-one heading would be invalid in a document that already
	// has one, so match the depth of what is already there.
	heading := "# "
	if strings.Contains(doc, "\n# ") || strings.HasPrefix(doc, "# ") {
		heading = "## "
	}

	lines := strings.Split(strings.TrimRight(doc, "\n"), "\n")
	if start, end, level := findSection(lines, taskSectionTitle); start >= 0 {
		replacement := append([]string{strings.Repeat("#", level) + " " + taskSectionTitle, "", section}, lines[end:]...)
		return strings.Join(append(lines[:start], replacement...), "\n") + "\n", true
	}

	if doc = strings.TrimRight(doc, "\n"); doc == "" {
		return heading + taskSectionTitle + "\n\n" + section + "\n", true
	}
	return doc + "\n\n" + heading + taskSectionTitle + "\n\n" + section + "\n", true
}

// findSection locates a heading by title and returns the line range it covers
// (up to the next heading of the same or higher level) plus its level.
func findSection(lines []string, title string) (start, end, level int) {
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		hashes := len(trimmed) - len(strings.TrimLeft(trimmed, "#"))
		if hashes == 0 || !strings.EqualFold(strings.TrimSpace(trimmed[hashes:]), title) {
			continue
		}

		for j := i + 1; j < len(lines); j++ {
			next := strings.TrimSpace(lines[j])
			depth := len(next) - len(strings.TrimLeft(next, "#"))
			if depth > 0 && depth <= hashes && strings.HasPrefix(next[depth:], " ") {
				return i, j, hashes
			}
		}
		return i, len(lines), hashes
	}
	return -1, -1, 0
}

// taskGuide is the agent-facing cheat sheet stored next to the tasks. It is
// generated so it cannot drift from the statuses, priorities and exit codes the
// binary actually implements.
func taskGuide(taskDir string) []byte {
	return fmt.Appendf(nil, `%s

# Task queue

This directory is a `+"`tq`"+` task queue: one Markdown file per task, named
`+"`<id>-<title-slug>.md`"+`, with YAML frontmatter. The files are the source of
truth and are meant to be committed.

Use the CLI rather than editing files by hand — it validates, keeps timestamps
and filenames in sync, and writes atomically. Every command below works from any
subdirectory of the repository.

## Pick up work

    tq ready --json                 tasks that are unblocked and unclaimed
    tq show <id> --json             the full task, body included
    tq move <id> in-progress        claim it

## Report progress

    tq note <id> "what happened"    append a timestamped note
    tq done <id>                    finish it
    tq move <id> <status>           any other transition

## Find things

    tq list --json                  every task
    tq list --status todo --label backend --priority high --assignee agent-api
    ls %s | grep auth               filenames carry a slug of the title
    grep -ril "oidc" %s             full-text search across tasks

## Create and change

    tq add "Title" --priority high --label backend --depends-on TQ-0002 --body "…"
    tq update <id> --title "New title" --assignee agent-api
    tq update <id> --add-label auth --remove-label backend
    tq update <id> --add-dependency TQ-0002 --remove-dependency TQ-0003

Arguments starting with "-" go after "--": tq note <id> -- "-1 test failing".

## Rules of the format

- Statuses: %s
- Priorities: %s (default: %s)
- A task is *ready* when it is neither done nor in-progress and every task in
  `+"`depends_on`"+` exists and is done. A missing dependency blocks it.
- `+"`--json`"+` prints JSON to stdout and nothing else; errors go to stderr.
- Exit codes: 0 success, 1 validation error, 2 task not found, 3 task directory
  missing and uncreatable.

## Where the tasks live

    %s

Set `+"`%s`"+` to point tq at a different task directory.
`,
		generatedNotice,
		filepath.Base(taskDir), filepath.Base(taskDir),
		strings.Join(Statuses, ", "),
		strings.Join(Priorities, ", "), PriorityNormal,
		taskDir,
		EnvTaskDir,
	)
}
